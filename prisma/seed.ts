function parseDates(item: any) {
  const result: any = { ...item }
  for (const key of Object.keys(result)) {
    if (typeof result[key] === 'string' && /^\d{4}-\d{2}-\d{2}T/.test(result[key])) {
      result[key] = new Date(result[key])
    }
  }
  return result
}

